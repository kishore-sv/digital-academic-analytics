# MODEL 3 — AT-RISK DETECTION
# CELL 4: WEIGHTED RISK SCORING ENGINE
# ============================================

def calculate_risk_score(row):
    """
    Calculate a 0-100 academic risk score.

    Higher score = higher academic risk.
    """

    score = 0.0

    # ----------------------------------------
    # 1. Attendance Risk — 20%
    # ----------------------------------------

    attendance = row["attendance_percentage"]

    if attendance < 60:
        attendance_risk = 1.0
    elif attendance < 75:
        attendance_risk = 0.70
    elif attendance < 85:
        attendance_risk = 0.30
    else:
        attendance_risk = 0.0

    score += attendance_risk * 20

    # ----------------------------------------
    # 2. Previous CGPA Risk — 20%
    # ----------------------------------------

    cgpa = row["previous_cgpa"]

    if pd.isna(cgpa):
        # Neutral risk when previous CGPA
        # is unavailable for early semesters
        cgpa_risk = 0.50

    elif cgpa < 5.0:
        cgpa_risk = 1.0
    elif cgpa < 6.0:
        cgpa_risk = 0.75
    elif cgpa < 7.0:
        cgpa_risk = 0.45
    elif cgpa < 8.0:
        cgpa_risk = 0.20
    else:
        cgpa_risk = 0.0

    score += cgpa_risk * 20

    # ----------------------------------------
    # 3. Backlog Risk — 20%
    # ----------------------------------------

    backlogs = row["backlog_count"]

    if backlogs >= 4:
        backlog_risk = 1.0
    elif backlogs == 3:
        backlog_risk = 0.80
    elif backlogs == 2:
        backlog_risk = 0.60
    elif backlogs == 1:
        backlog_risk = 0.30
    else:
        backlog_risk = 0.0

    score += backlog_risk * 20

    # ----------------------------------------
    # 4. Current Failed Courses — 15%
    # ----------------------------------------

    failed_courses = row["current_failed_courses"]

    if failed_courses >= 3:
        failed_risk = 1.0
    elif failed_courses == 2:
        failed_risk = 0.75
    elif failed_courses == 1:
        failed_risk = 0.50
    else:
        failed_risk = 0.0

    score += failed_risk * 15

    # ----------------------------------------
    # 5. Low Performance Courses — 10%
    # ----------------------------------------

    low_courses = row["low_performance_course_count"]

    if low_courses >= 4:
        low_performance_risk = 1.0
    elif low_courses == 3:
        low_performance_risk = 0.75
    elif low_courses == 2:
        low_performance_risk = 0.50
    elif low_courses == 1:
        low_performance_risk = 0.25
    else:
        low_performance_risk = 0.0

    score += low_performance_risk * 10

    # ----------------------------------------
    # 6. Study Hours Risk — 5%
    # ----------------------------------------

    study_hours = row["study_hours_per_week"]

    if study_hours < 10:
        study_risk = 1.0
    elif study_hours < 15:
        study_risk = 0.60
    elif study_hours < 20:
        study_risk = 0.30
    else:
        study_risk = 0.0

    score += study_risk * 5

    # ----------------------------------------
    # 7. Assignment Completion Risk — 5%
    # ----------------------------------------

    assignment_completion = row[
        "assignment_completion_percentage"
    ]

    if assignment_completion < 50:
        assignment_risk = 1.0
    elif assignment_completion < 70:
        assignment_risk = 0.60
    elif assignment_completion < 85:
        assignment_risk = 0.30
    else:
        assignment_risk = 0.0

    score += assignment_risk * 5

    # ----------------------------------------
    # 8. Performance Trend Risk — 5%
    # ----------------------------------------

    trend = row["performance_trend"]

    if trend == "DECLINING":
        trend_risk = 1.0
    elif trend == "STABLE":
        trend_risk = 0.30
    else:  # IMPROVING
        trend_risk = 0.0

    score += trend_risk * 5

    return round(score, 2)


